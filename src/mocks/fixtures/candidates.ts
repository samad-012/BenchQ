import type { Candidate, Persona, QaBankEntry } from "@/lib/schemas/candidate";
import { daysAgo, daysFromNow, hoursAgo, resetSeed, seededRandom } from "./_seed";

resetSeed(200);

function qaId(candidateId: string, n: number): string {
  return `qa_${candidateId}_${n}`;
}

function makePersona(overrides: Partial<Persona>): Persona {
  return {
    summary: overrides.summary ?? "",
    toneNotes: overrides.toneNotes ?? null,
    willRelocate: overrides.willRelocate ?? true,
    noticePeriodDays: overrides.noticePeriodDays ?? null,
    preferredIndustries: overrides.preferredIndustries ?? [],
    dealBreakers: overrides.dealBreakers ?? [],
  };
}

function makeQa(
  candidateId: string,
  entries: Array<Pick<QaBankEntry, "question" | "answer" | "category"> & { state?: QaBankEntry["state"] }>,
): QaBankEntry[] {
  return entries.map((e, i) => ({
    id: qaId(candidateId, i),
    question: e.question,
    answer: e.answer,
    category: e.category,
    useCount: Math.floor(seededRandom() * 10),
    lastUsedAt: seededRandom() > 0.3 ? hoursAgo(Math.floor(seededRandom() * 72)) : null,
    state: e.state ?? "VERIFIED",
    evidenceId: (e.state ?? "VERIFIED") === "VERIFIED" ? `ev_${candidateId}_qa_${i}` : null,
  }));
}

